          Fakultas  Peternakan  (Faterna)  Universitas  Andalas  didirikan  tanggal 1 September 1963,  atas  ketetapan  Menteri  Perguruan  Tinggi  dan Ilmu  Pengetahuan  (PTIP)  dengan  Surat  Keputusan  No.  125  tanggal 9 Oktober 1963 yang ditetapkan di Jakarta tanggal 9 Oktober 1963. Berdasarkan urutan pendiriannya, Faterna merupakan Fakultas keenam dari lima belas Fakultas di lingkungan Universitas Andalas. Pendirian Faterna dilatarbelakangi oleh perkembangan ilmu-ilmu pertanian yang dibutuhkan dalam pembangunan Indonesia dan perluasan Universitas Andalas. Pada awal berdiri sampai dengan tahun 1991 Faterna berlokasi di Kampus Unand Air Tawar, Padang dan sejak Semester Ganjil 1991/1992 pindah ke Kampus Unand di Limau Manis, Padang. <br> <br>

